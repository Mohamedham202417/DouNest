let current = localStorage.getItem("toolnest.lang");
if (!current) {
  const nav = (navigator.language || "en").slice(0, 2);
  current = T[nav] ? nav : "en";
}

export function t(key) {
  return T[current]?.[key] ?? T.en[key] ?? key;
}
export function getLang() { return current; }
export function setLang(code) {
  if (!T[code]) code = "en";
  current = code;
  localStorage.setItem("toolnest.lang", code);
  const meta = getLangMeta(code);
  document.documentElement.lang = code;
  document.documentElement.dir = meta.dir;
  applyTranslations();
  document.dispatchEvent(new CustomEvent("langchange", { detail: { code } }));
}
export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
}

